#!/usr/bin/env node
// Writes apps/web/.env.local and apps/worker/.env for LOCAL development from .local/db.env.
// Generates a local envelope-encryption master key and a download-token secret once; existing
// values are never overwritten (rotating VEIL_MASTER_KEY would make stored data unreadable).
//
//   node scripts/dev-db.mjs start && node scripts/setup-env.mjs
//
// Hosted deployments must NOT use this script: supply values from a secret manager instead.

import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");

function parse(file) {
  if (!existsSync(file)) return {};
  return Object.fromEntries(
    readFileSync(file, "utf8")
      .split(/\r?\n/)
      .filter((l) => l.includes("=") && !l.startsWith("#"))
      .map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1)]),
  );
}

const db = parse(join(root, ".local", "db.env"));
if (!db.DATABASE_URL) {
  console.error("Run `node scripts/dev-db.mjs start` first (no .local/db.env).");
  process.exit(1);
}

function write(file, values, header) {
  const existing = parse(file);
  const merged = { ...values, ...existing }; // never overwrite existing secrets/choices
  const body = [header, ...Object.entries(merged).map(([k, v]) => `${k}=${v}`), ""].join("\n");
  writeFileSync(file, body, { mode: 0o600 });
  const added = Object.keys(values).filter((k) => !(k in existing));
  console.log(`${file}: ${added.length ? `added ${added.join(", ")}` : "unchanged"}`);
}

const shared = {
  NEAR_NETWORK: "testnet",
  NEAR_RPC_URL: "https://test.rpc.fastnear.com",
  NEAR_EXPLORER_URL: "https://testnet.nearblocks.io",
  // Set after the human approves and performs the testnet deployment (docs/DEPLOYMENTS.md).
  NEAR_CONTRACT_ID: "",
};

const masterKey = randomBytes(32).toString("base64");

write(
  join(root, "apps", "web", ".env.local"),
  {
    APP_URL: "http://localhost:3000",
    DATABASE_URL: db.DATABASE_URL,
    VEIL_MASTER_KEY: masterKey,
    VEIL_KEY_ID: "local-dev-1",
    DOWNLOAD_TOKEN_SECRET: randomBytes(32).toString("base64"),
    STORAGE_DIR: join(root, ".local", "objects").replaceAll("\\", "/"),
    // dev-mailbox: e-mails are stored and shown at /dev/mailbox (never in production).
    EMAIL_TRANSPORT: "dev-mailbox",
    ...shared,
  },
  "# Local development only — generated by scripts/setup-env.mjs. Never commit.",
);

const web = parse(join(root, "apps", "web", ".env.local"));
write(
  join(root, "apps", "worker", ".env"),
  {
    WORKER_DATABASE_URL: db.WORKER_DATABASE_URL,
    VEIL_MASTER_KEY: web.VEIL_MASTER_KEY,
    VEIL_KEY_ID: web.VEIL_KEY_ID,
    NEARAI_BASE_URL: "https://cloud-api.near.ai",
    // Required for confidential AI evaluation; leave empty until the human provides a key.
    NEARAI_API_KEY: "",
    NEARAI_MODEL: "",
    ...shared,
  },
  "# Local development only — generated by scripts/setup-env.mjs. Never commit.",
);
