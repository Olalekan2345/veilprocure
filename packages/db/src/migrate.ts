import { drizzle } from "drizzle-orm/postgres-js";
import { migrate } from "drizzle-orm/postgres-js/migrator";
import postgres from "postgres";
import { existsSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

/** Applies migrations as the schema owner. Usage: MIGRATION_DATABASE_URL=... tsx src/migrate.ts */
export async function runMigrations(url: string): Promise<void> {
  const client = postgres(url, { max: 1, onnotice: () => {} });
  try {
    await migrate(drizzle(client), { migrationsFolder: fileURLToPath(new URL("../migrations", import.meta.url)) });
  } finally {
    await client.end({ timeout: 5 });
  }
}

/** Local development fallback: credentials generated by scripts/dev-db.mjs. */
function localMigrationUrl(): string | undefined {
  const file = fileURLToPath(new URL("../../../.local/db.env", import.meta.url));
  if (!existsSync(file)) return undefined;
  const prefix = "MIGRATION_DATABASE_URL=";
  const line = readFileSync(file, "utf8")
    .split("\n")
    .map((l) => l.trim())
    .find((l) => l.startsWith(prefix));
  return line?.slice(prefix.length);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const url = process.env.MIGRATION_DATABASE_URL ?? localMigrationUrl();
  if (!url) {
    console.error("MIGRATION_DATABASE_URL is required (schema owner connection string)");
    process.exit(1);
  }
  runMigrations(url)
    .then(() => console.log("migrations applied"))
    .catch((err: unknown) => {
      console.error("migration failed:", err instanceof Error ? err.message : err);
      process.exit(1);
    });
}
